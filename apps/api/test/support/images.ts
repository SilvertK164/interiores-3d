/** Un cuerpo válido de `POST /v1/analyze-room`; `extra` pisa o agrega campos. */
export const analyzeBody = (extra: Record<string, unknown> = {}) => ({ image: b64(JPEG), mime: 'image/jpeg', catalog: CATALOG, ...extra })
